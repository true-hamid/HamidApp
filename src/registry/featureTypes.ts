import type React from 'react';

import type {StackNavigatorId, TabNavigatorId} from '@navigation/navigators';

type LazyScreen = () => React.ComponentType<any>;

/** Translation bundles per language, e.g. {en: {...}, ar: {...}}. */
export type I18nBundles = Record<string, object>;

type ScreenBase = {
  name: string;
  getComponent: LazyScreen;
};

/** How a screen appears in a tab bar. `index` is its position (unique per navigator). */
export type TabInfo = {
  index: number;
  icon: string;
  labelKey: string;
};

/** A screen of a tab navigator. */
export type TabScreen = ScreenBase & {
  navigator: TabNavigatorId;
  tab: TabInfo;
  titleKey?: never;
};

/** A screen of a stack navigator. */
export type StackScreen = ScreenBase & {
  navigator: StackNavigatorId;
  /** Header title (shared-namespace key). Defaults to the screen name. */
  titleKey?: string;
  tab?: never;
};

export type FeatureScreen = TabScreen | StackScreen;

/** What a feature tells the navigation shell about itself. */
export type FeatureModule = {
  /**
   * Lazily returns the feature's translations. They are registered as the
   * namespace named after the feature's id (its folder name), the first time any of the
   * feature's screens is requested, so nothing is loaded for features never
   * opened.
   */
  i18n?: () => I18nBundles;
  screens: FeatureScreen[];
};

/**
 * Generated by babel/featuresPlugin.js. `id` is the feature's folder name;
 * `load` evaluates its manifest, nothing runs until then.
 */
export type FeatureLoader = {id: string; load: () => FeatureModule};
